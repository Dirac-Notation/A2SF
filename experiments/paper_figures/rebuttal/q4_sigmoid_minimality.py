"""Q4 rebuttal: Sigmoid is the minimal parametric family for Observation 1.

Argument: Obs 1 (paper) showed the per-prompt optimal coefficient w_d* lies in
a sigmoid-shaped band. The reviewer asks why we *use* sigmoid in the method.
Answer: among interpretable parametric families, sigmoid is the unique 2-param
family that captures both degrees of freedom Obs 1 reveals — transition
midpoint (b) and transition sharpness (a). We verify this by re-fitting the
per-prompt optimal weight curves with alternatives.

Data source (paper-aligned):
  experiments/temporal_bias/plots/<Task>/<dataset>/coord_descent.npz
  → "w_cd" key, shape (N=10 prompts, W=128 query distances)
  generated by coord_descent.py (paper Appendix C.2 forward-greedy under
  set-Jaccard "Tanimoto" similarity).

Per-prompt fits avoid the "mean curve ≠ any real prompt" concern: we fit each
of the 10 prompts in each task independently, then average R² across prompts.

Procedure:
  - Load w_cd (N, W) per task.
  - For each prompt curve, fit four parametric families:
        sigmoid w(d) = 1 / (1 + exp(a (d - b)))      [2 params]
        step    w(d) = 1 / (1 + exp(50 (d - b)))     [1 param, hard cutoff]
        exp     w(d) = exp(-d / tau)                 [1 param]
        linear  w(d) = max(0, 1 - d / W_eff)         [1 param]
  - Compute R² of each fit against that prompt's w_cd vector.
  - Aggregate: mean R² across prompts per task and per family.
  - Plot: paper-style 4-panel layout, band + mean curve + 4-family fits
          (visual fits to the MEAN; the R² numbers shown in the panel are
          per-prompt averages, not mean-curve R²).

Output:
  experiments/paper_figures/rebuttal/q4_obs1_with_alternatives.{pdf,png}
  experiments/paper_figures/rebuttal/q4_summary.json
"""
import os, json
import numpy as np
import matplotlib.pyplot as plt
from matplotlib import rcParams
from scipy.optimize import curve_fit

rcParams.update({
    "font.family": "serif", "font.size": 12,
    "axes.labelsize": 13, "axes.titlesize": 14,
    "xtick.labelsize": 10, "ytick.labelsize": 10,
    "legend.fontsize": 9, "axes.linewidth": 1.0,
    "figure.dpi": 150,
})

PLOTS_BASE = "/home/smp9898/A2SF/experiments/temporal_bias/plots"
OUT_DIR    = "/home/smp9898/A2SF/experiments/paper_figures/rebuttal"

TASKS = [
    ("Single-doc_QA/qasper",     "Single-doc QA"),
    ("Multi-doc_QA/hotpotqa",    "Multi-doc QA"),
    ("Summarization/gov_report", "Summarization"),
    ("Few_Shot/samsum",          "Few-Shot"),
]


# Function families
def sigmoid(d, a, b):
    return 1.0 / (1.0 + np.exp(np.clip(a * (d - b), -30.0, 30.0)))


def step_fn(d, b):
    return 1.0 / (1.0 + np.exp(np.clip(50.0 * (d - b), -30.0, 30.0)))


def exp_decay(d, tau):
    return np.exp(-d / max(tau, 1e-6))


def linear_decay(d, W_eff):
    return np.clip(1.0 - d / max(W_eff, 1e-6), 0.0, 1.0)


def fit_family(d, y, fn, p0, bounds):
    """Returns (R², params, y_pred)."""
    try:
        popt, _ = curve_fit(fn, d.astype(float), y, p0=p0, bounds=bounds, maxfev=20000)
        y_pred = fn(d, *popt)
        ss_res = np.sum((y - y_pred) ** 2)
        ss_tot = np.sum((y - y.mean()) ** 2)
        r2 = 1.0 - ss_res / ss_tot if ss_tot > 1e-12 else 0.0
        return float(r2), [float(v) for v in popt], y_pred
    except Exception:
        return float("nan"), None, None


def fit_all_families(d, y, W):
    """Fit all 4 families to a single curve. Returns dict {family: (R², params, y_pred)}."""
    return {
        "sigmoid": fit_family(d, y, sigmoid,
                               p0=[0.1, W / 4.0],
                               bounds=([0.001, -W * 0.5], [50, W * 1.5])),
        "step":    fit_family(d, y, step_fn,
                               p0=[W / 4.0],
                               bounds=([0.0], [W * 1.5])),
        "exp":     fit_family(d, y, exp_decay,
                               p0=[W / 4.0],
                               bounds=([0.5], [W * 5.0])),
        "linear":  fit_family(d, y, linear_decay,
                               p0=[W / 2.0],
                               bounds=([1.0], [W * 5.0])),
    }


def main():
    os.makedirs(OUT_DIR, exist_ok=True)

    results = {}
    fig, axes = plt.subplots(1, 4, figsize=(15, 3.8))
    color_band = "steelblue"
    family_colors = {
        "sigmoid": "black",
        "step":    "tab:red",
        "exp":     "tab:orange",
        "linear":  "tab:green",
    }

    for col, (path, label) in enumerate(TASKS):
        npz = f"{PLOTS_BASE}/{path}/coord_descent.npz"
        if not os.path.exists(npz):
            print(f"[skip] {label}: missing {npz} (run coord_descent.py first)")
            continue

        d_npz = np.load(npz)
        w_cd  = d_npz["w_cd"]              # (N=10, W=128) per-prompt optimal w
        chunk = int(d_npz["chunk"])
        W     = int(d_npz["window"])
        N, G  = w_cd.shape
        d_c   = np.arange(G) * chunk + (chunk - 1) / 2.0

        # band (min-max) and mean — same as obs1_sigmoid_band visualization
        w_min  = w_cd.min(axis=0)
        w_max  = w_cd.max(axis=0)
        w_mean = w_cd.mean(axis=0)

        # ── Per-prompt fit → R² array per family ─────────────────────
        per_prompt_r2 = {fam: [] for fam in ["sigmoid", "step", "exp", "linear"]}
        per_prompt_params = {fam: [] for fam in per_prompt_r2}
        for n in range(N):
            fits = fit_all_families(d_c, w_cd[n], W)
            for fam, (r2, params, _) in fits.items():
                per_prompt_r2[fam].append(r2)
                per_prompt_params[fam].append(params)

        # Aggregate
        agg = {fam: {
            "mean_R2":   float(np.nanmean(r2s)),
            "median_R2": float(np.nanmedian(r2s)),
            "std_R2":    float(np.nanstd(r2s)),
            "n":         int(np.sum(~np.isnan(r2s))),
        } for fam, r2s in per_prompt_r2.items()}

        # Visual fits to MEAN (for plotting only — labels show *per-prompt avg* R²)
        mean_fits = fit_all_families(d_c, w_mean, W)

        results[label] = {
            "per_prompt": {fam: [float(x) for x in r2s] for fam, r2s in per_prompt_r2.items()},
            "agg":        agg,
            "mean_curve_fit": {fam: {"R2": fits[0], "params": fits[1]}
                                for fam, fits in mean_fits.items()},
        }

        # Plot
        ax = axes[col]
        ax.fill_between(d_c, w_min, w_max, color=color_band, alpha=0.20,
                         linewidth=0, label="prompt range")
        ax.plot(d_c, w_mean, color="steelblue", lw=1.8, alpha=0.95,
                label="mean across prompts")
        for fam in ["sigmoid", "step", "exp", "linear"]:
            _, _, y_pred = mean_fits[fam]
            if y_pred is None: continue
            r2_avg = agg[fam]["mean_R2"]
            ax.plot(d_c, y_pred, "--", color=family_colors[fam], lw=1.5,
                    label=f"{fam}  $\\overline{{R^2}}$={r2_avg:.2f}")

        ax.set_xlim(0, W - 1)
        ax.invert_xaxis()
        ax.set_ylim(-0.05, 1.10)
        ax.set_title(label)
        ax.grid(True, alpha=0.3)
        ax.set_xlabel(r"distance $d$  ($\leftarrow$ older $\cdot$ recent $\rightarrow$)")
        if col == 0:
            ax.set_ylabel(r"optimal coefficient  $w_d^*$")
            ax.legend(loc="lower left", fontsize=8.5, framealpha=0.95)

    fig.suptitle("Per-prompt fit of $w_d^*$ to four parametric families  "
                 "($\\overline{R^2}$ = mean over N=10 prompts per task)",
                 y=1.02)
    fig.tight_layout()
    out_pdf = f"{OUT_DIR}/q4_obs1_with_alternatives.pdf"
    fig.savefig(out_pdf, bbox_inches="tight")
    fig.savefig(out_pdf.replace(".pdf", ".png"), bbox_inches="tight")
    plt.close(fig)
    print(f"saved → {out_pdf}")

    # Summary
    out_json = f"{OUT_DIR}/q4_summary.json"
    with open(out_json, "w") as f:
        json.dump(results, f, indent=2)
    print(f"saved → {out_json}")
    print()
    print(f"{'Task':22s}  {'sigmoid':>14}  {'step':>14}  {'exp':>14}  {'linear':>14}")
    print("─" * 90)
    for label, r in results.items():
        s = r["agg"]
        print(f"{label:22s}  "
              + "  ".join(f"{s[f]['mean_R2']:6.3f}±{s[f]['std_R2']:5.3f}"
                           for f in ["sigmoid", "step", "exp", "linear"]))


if __name__ == "__main__":
    main()
